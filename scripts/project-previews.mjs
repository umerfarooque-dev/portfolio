/** Build small, ready-to-serve hover screenshots from the local cover captures. */
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import sharp from "sharp";

const directory = "public/projects/previews";
// These old captures contain the capture service's spinner, not a website.
// Match the bytes rather than filenames so a replacement capture is accepted.
const spinnerHash = "ed3eb0ae64af44cc1bd9e9606f447faf8a941b9f2a0bed763b8fb59adcc16285";
await mkdir(directory, { recursive: true });
const previews = {};
const unavailable = [];
let bytes = 0;
for (const file of await readdir("public/projects")) {
    if (!file.endsWith(".webp")) continue;
    const source = `/projects/${file}`;
    const input = await readFile(`public${source}`);
    if (createHash("sha256").update(input).digest("hex") === spinnerHash) { unavailable.push(source); continue; }
    const output = await sharp(input)
        .resize({ width: 680, height: 480, fit: "cover", position: "top" })
        .webp({ quality: 72 })
        .toBuffer();
    await writeFile(`${directory}/${file}`, output);
    previews[source] = `/projects/previews/${file}`;
    bytes += output.length;
}
await writeFile("src/data/project-previews.ts",
    `/** Generated by scripts/project-previews.mjs from local screenshot assets. */\nexport const PROJECT_PREVIEWS: Record<string, string> = ${JSON.stringify(previews, null, 4)};\nexport const UNAVAILABLE_PROJECT_IMAGES: string[] = ${JSON.stringify(unavailable, null, 4)};\n`);
console.log(`${Object.keys(previews).length} local previews, ${Math.round(bytes / 1024)} KB total`);
